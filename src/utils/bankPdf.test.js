import { DEFAULT_CATEGORIES } from '../data/mockData.js';
import { sberLinesToRows } from './bankPdf.js';
import { rowsToDrafts } from './statement.js';

// Строки текста, как их собирает pdfToLines из samples/sber-vypiska-primer.pdf (фрагмент)
const LINES = [
  'Выписка по счёту дебетовой карты',
  'Период: 01.09.2026 — 27.10.2026',
  'Остаток на 01.09.2026: 20 000,00',
  'ДАТА ОПЕРАЦИИ (МСК) КАТЕГОРИЯ СУММА В ВАЛЮТЕ СЧЁТА ОСТАТОК СРЕДСТВ В ВАЛЮТЕ СЧЁТА',
  '01.09.2026 10:15 Зарплата +85 000,00 105 000,00',
  '01.09.2026 ООО «Ромашка». Заработная плата за август',
  '02.09.2026 18:40 Супермаркеты 2 340,50 102 659,50',
  '02.09.2026 214365 PRODUKTY U DOMA Moskva RUS. Операция по карте ****0000',
  '03.09.2026 08:12 Транспорт 54,00 102 605,50',
  '03.09.2026 587120 METRO Moskva RUS. Операция по карте ****0000',
  '03.09.2026 08:12 Транспорт 54,00 102 551,50',
  '03.09.2026 587121 METRO Moskva RUS. Операция по карте ****0000',
  '10.09.2026 09:00 Перевод с карты 10 000,00 88 871,50',
  '10.09.2026 Перевод между своими счетами. На накопительный счёт ****1111',
  '15.09.2026 11:20 Прочие поступления +4 990,00 88 871,50',
  '15.09.2026 771204 Возврат покупки. MODNY DOM Moskva RUS',
  '25.09.2026 12:00 Коммунальные платежи, связь, интернет 1 006 200,00 84 171,50',
  'Страница 1 из 1',
];

describe('PDF-выписка Сбербанка', () => {
  it('две строки на операцию: дата, категория, сумма со знаком и описание', () => {
    const rows = sberLinesToRows(LINES);
    expect(rows[0]).toEqual(['дата', 'категория', 'сумма платежа', 'комментарий']);
    expect(rows.slice(1, 3)).toEqual([
      ['01.09.2026 10:15', 'Зарплата', '85 000,00', 'ООО «Ромашка». Заработная плата за август'],
      ['02.09.2026 18:40', 'Супермаркеты', '-2 340,50', 'PRODUKTY U DOMA Moskva RUS. Операция по карте ****0000'],
    ]);
    // Длинная категория с запятыми и сумма больше миллиона; описания у последней операции нет
    expect(rows.at(-1)).toEqual(['25.09.2026 12:00', 'Коммунальные платежи, связь, интернет', '-1 006 200,00', '']);
    expect(rows).toHaveLength(8);
  });

  it('общий разбор: зарплата, две одинаковые поездки, перевод между своими счетами и возврат', () => {
    const { drafts } = rowsToDrafts(sberLinesToRows(LINES), { categories: DEFAULT_CATEGORIES, existing: [], today: new Date(2026, 9, 28) });
    // Категории Сбербанка разносятся словарём: «Супермаркеты» → «Еда», «Коммунальные платежи…» → «Жильё»
    expect(drafts.map((d) => [d.type, d.amount, d.incoming, d.categoryId])).toEqual([
      ['income', 85000, true, 'salary'],
      ['expense', 2341, false, 'food'],
      ['expense', 54, false, 'transport'],
      ['expense', 54, false, 'transport'],
      ['transfer', 10000, false, null],
      ['expense', 4990, true, 'other'],
      ['expense', 1006200, false, 'housing'],
    ]);
  });

  it('в PDF без операций — пустой результат', () => {
    expect(sberLinesToRows(['Справка о наличии счёта', 'Остаток: 1 000,00'])).toEqual([]);
  });
});
